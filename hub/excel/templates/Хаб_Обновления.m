// Таблица «Хаб_Обновления»: когда какие ряды модели обновлялись — строка на «загрузка × ряд»:
// Обновлено (дата и время) | Дата обновления | Что (первая загрузка / новые данные / уточнение прошлых периодов) |
// Новых значений | Изменено значений | Период с | Период по | Код | Название | Показатель | Периодичность | Источник.
// Свежие сверху. Чтобы увидеть, что изменилось с последнего пересчёта модели, отфильтруйте «Обновлено» позже его даты.
// Файл лежит рядом с посылкой: «<модель> — обновления.csv».
let
    Путь = Text.Start(Хаб_Посылка, Text.Length(Хаб_Посылка) - 4) & " — обновления.csv",
    Байты = try Binary.Buffer(File.Contents(Путь)) otherwise null,
    Файл = if Байты = null
        then error Error.Record(
            "Хаб: не найдена история обновлений",
            "Не найден файл " & Путь & ". Откройте «Хаб данных» и нажмите «Обновить всё сейчас».",
            Путь)
        else Байты,
    Csv = Csv.Document(Файл, [Delimiter = ";", Encoding = 65001, QuoteStyle = QuoteStyle.Csv]),
    Заголовки = Table.PromoteHeaders(Csv, [PromoteAllScalars = true]),
    ПустыеВNull = Table.ReplaceValue(Заголовки, "", null, Replacer.ReplaceValue, {"Период с", "Период по"}),
    Типы = Table.TransformColumnTypes(
        ПустыеВNull,
        {{"Обновлено", type datetime}, {"Дата обновления", type date}, {"Что", type text},
         {"Новых значений", Int64.Type}, {"Изменено значений", Int64.Type}, {"Период с", type date},
         {"Период по", type date}, {"Код", type text}, {"Название", type text}, {"Показатель", type text},
         {"Периодичность", type text}, {"Источник", type text}},
        "en-US")
in
    Типы
